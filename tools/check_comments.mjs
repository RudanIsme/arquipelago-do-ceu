// Comentário no máximo em 2 linhas seguidas: o código diz o quê, o comentário só o porquê.
// Uso: node tools/check_comments.mjs [pasta ...]   (sem argumentos, varre core, game, game.tests e tools)
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const limite = 2;
const raiz = process.cwd();
const pastas = process.argv.length > 2 ? process.argv.slice(2) : ['core', 'game', 'game.tests', 'tools'];
const ignorar = new Set(['bin', 'obj', '.godot', 'node_modules', '.git']);

function* arquivos(pasta) {
  for (const nome of readdirSync(pasta)) {
    if (ignorar.has(nome)) continue;
    const caminho = join(pasta, nome);
    if (statSync(caminho).isDirectory()) yield* arquivos(caminho);
    else if (caminho.endsWith('.cs') || caminho.endsWith('.mjs')) yield caminho;
  }
}

// Linha que é só comentário (não conta o que acompanha código na mesma linha).
const ehComentario = (linha) => /^\s*\/\//.test(linha);
// Cabeçalho gerado e diretivas não contam.
const ehIsento = (linha) => /^\s*\/\/\s*(<auto-generated|pragma|nullable|noqa)/i.test(linha);

const violacoes = [];
for (const pasta of pastas) {
  for (const arquivo of arquivos(pasta)) {
    const linhas = readFileSync(arquivo, 'utf8').split(/\r?\n/);
    let inicio = -1;
    const fecha = (fim) => {
      if (inicio >= 0 && fim - inicio > limite) violacoes.push(`${relative(raiz, arquivo).split(sep).join('/')}:${inicio + 1}: comentário de ${fim - inicio} linhas (máximo ${limite})`);
      inicio = -1;
    };
    linhas.forEach((linha, i) => {
      if (ehComentario(linha) && !ehIsento(linha)) {
        if (inicio < 0) inicio = i;
      } else fecha(i);
    });
    fecha(linhas.length);
  }
}

if (violacoes.length > 0) {
  console.error(violacoes.join('\n'));
  console.error(`\n${violacoes.length} comentário(s) acima de ${limite} linhas. Encurte ou melhore o nome do código.`);
  process.exit(1);
}
console.log('Comentários dentro do limite.');
